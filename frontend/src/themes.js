const applyOverrides = (themes, overrides) =>
    Object.fromEntries(
        Object.entries(themes).map(([key, theme]) => [
            key,
            { ...overrides, ...theme },
        ]),
    );

export const themes = {
    light: applyOverrides(lightThemes, lightOverrides),
    dark: applyOverrides(darkThemes, darkOverrides),
};
